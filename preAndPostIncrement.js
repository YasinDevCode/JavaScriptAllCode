// Syntax of pre and post increment
// Pre-increment: ++variable
// Post-increment: variable++


// pre-increment: ++variable
let x = 5;
console.log(++x); // Output: 6
console.log(x); // Output: 6

// Real life Example
let score = 10;
console.log(++score); // Output: 11
console.log(score); // Output: 11



// post -increment: variable++

let y = 5;
console.log(y++); // Output: 5
console.log(y); // Output: 6
// Real life Example
let points = 20;
console.log(points++); // Output: 20
console.log(points); // Output: 21